<?php

/**
 * ORD-PC: builds `resources/data/bg-postcodes.php` from the GeoNames postal-code file for Bulgaria.
 *
 *   php scripts/data/build-bg-postcodes.php [path/to/BG.zip | path/to/BG.txt]
 *
 * With no argument it downloads https://download.geonames.org/export/zip/BG.zip. GeoNames postal codes: https://www.geonames.org, licence CC BY 4.0
 * (https://creativecommons.org/licenses/by/4.0/). The output keeps, per postcode, the settlement names in Bulgarian and the GeoNames admin1 CODE
 * (the file's own region NAMES are not used: they contain errors, e.g. a Stara Zagora code under the name «Смолян»; the names come from the fixed table
 * App\Support\BgRegions). Row format of the source (tab separated): country, postcode, place «bg / latin», admin1 name, admin1 CODE, admin2 name, admin2 code, ...
 *
 * Output shape: ['p' => ['6450' => [['Харманли', 'HKV']], ...]] — a postcode maps to a list of [settlement, admin1 code] pairs, sorted by postcode.
 */
$root = dirname(__DIR__, 2);
$source = $argv[1] ?? 'https://download.geonames.org/export/zip/BG.zip';
$work = sys_get_temp_dir().'/bg-postcodes-'.bin2hex(random_bytes(4));
mkdir($work);

if (str_starts_with($source, 'http')) {
    $zip = $work.'/BG.zip';
    $bytes = @file_get_contents($source);

    if ($bytes === false) {
        fwrite(STDERR, "Cannot download {$source}: fetch BG.zip by hand and pass its path.\n");
        exit(1);
    }

    file_put_contents($zip, $bytes);
    $source = $zip;
}

if (str_ends_with(strtolower($source), '.zip')) {
    $archive = new ZipArchive();

    if ($archive->open($source) !== true || $archive->locateName('BG.txt') === false) {
        fwrite(STDERR, "{$source} is not the GeoNames BG.zip (no BG.txt inside).\n");
        exit(1);
    }

    $archive->extractTo($work, 'BG.txt');
    $source = $work.'/BG.txt';
}

require_once $root.'/app/Support/BgRegions.php';

$postcodes = [];
$skipped = 0;

foreach (file($source, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $line) {
    $cols = explode("\t", $line);
    $code = $cols[1] ?? '';
    $region = $cols[4] ?? '';
    $place = trim(explode(' / ', $cols[2] ?? '')[0]);

    if (($cols[0] ?? '') !== 'BG' || preg_match('/^\d{4}$/', $code) !== 1 || $place === '' || ! isset(App\Support\BgRegions::NAMES[$region])) {
        $skipped++;

        continue;
    }

    $postcodes[$code][$place.'|'.$region] = [$place, $region];
}

ksort($postcodes, SORT_STRING);
$out = [];

foreach ($postcodes as $code => $pairs) {
    ksort($pairs, SORT_STRING);
    $out[$code] = array_values($pairs);
}

$header = "<?php\n\n// GENERATED by scripts/data/build-bg-postcodes.php — do not edit by hand.\n"
    ."// Source: GeoNames postal codes for Bulgaria (https://download.geonames.org/export/zip/BG.zip), https://www.geonames.org,\n"
    ."// licensed under Creative Commons Attribution 4.0 (CC BY 4.0, https://creativecommons.org/licenses/by/4.0/).\n"
    .'// '.count($out)." postcodes. Shape: postcode => list of [settlement (bg), GeoNames admin1 code]; region NAMES come from App\\Support\\BgRegions.\n\n";

$q = static fn (string $v): string => var_export($v, true);
$lines = [];

foreach ($out as $code => $pairs) {
    $lines[] = '    '.$q((string) $code).' => ['.implode(', ', array_map(static fn (array $pair): string => '['.$q($pair[0]).', '.$q($pair[1]).']', $pairs)).'],';
}

$php = $header."return ['p' => [\n".implode("\n", $lines)."\n]];\n";
file_put_contents($root.'/resources/data/bg-postcodes.php', $php);

echo count($out).' postcodes written, '.$skipped.' source rows skipped, '.round(strlen($php) / 1024).' KB'."\n";
