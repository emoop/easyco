<?php

namespace App\Http\Middleware;

use Closure;
use EasyCo\Cart\Persistence\Eloquent\CartModel;
use Illuminate\Http\Request;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Cookie;
use Illuminate\Support\Str;
use Symfony\Component\HttpFoundation\Response;

/**
 * A guest's cart survives the session (cart-domain-design.md §10, "Guest cart persistence"; storefront-design.md §2.9).
 *
 * The guest cart is a database row keyed by `cart_token`, and the token lives in the Laravel SESSION (§8): when the
 * session ends (2 hours) the visitor keeps a perfectly good cart row they can no longer reach. This middleware mirrors the
 * token into a long-lived, ENCRYPTED, HttpOnly cookie, `easyco_cart`, and restores it into a new session:
 *
 *  - BEFORE the controller: no `cart_token` in the session, and a valid `easyco_cart` cookie -> the cookie's token is put
 *    into the session. The code that reads the token (CartController, CheckoutController, ShippingQuoteController,
 *    MergeGuestCartIntoAccountCart, ApiRateLimits) is UNCHANGED: it keeps reading the session.
 *  - AFTER the controller: the session has a token -> the cookie is (re)queued with it; the session has none (the merge
 *    listener forgot it at login, or the visitor never had one) -> a cookie that was sent is deleted.
 *
 * WHAT STAYS TRUE (cart-domain-design.md §8): the token is generated by the SERVER (Str::uuid() in CartController) and is
 * never chosen by a client. A cookie is accepted only if EncryptCookies could decrypt it (a plain-text or tampered value
 * arrives as null and is ignored) AND it is a UUID; a token in a body, header or query is read by nothing. The cookie
 * mirrors the session: it never creates a token, it only carries the one the server issued.
 *
 * LIFETIME, and "the cookie never outlives the cart row": `cart.guest_cookie_days` (default 7), capped by the time left on
 * the live cart row (`carts.expires_at`, which only a WRITE refreshes: 10 days, CartController::expiry()). The cookie is
 * therefore refreshed on a write (the same moments the row's life is), and NOT on a plain read (a read never extends a cart,
 * §9, so it must not extend the cookie): a read re-queues it only when the request carried no cookie yet. With no live row
 * (a claimed or pruned cart) the cookie is left as it is.
 *
 * THREE MODES, the middleware parameter: `cart.cookie:write` (cart line and promotion writes), `cart.cookie:read`
 * (GET /cart, the default) and `cart.cookie:passive` (checkout, shipping quote, login, register: restore the token and
 * delete the cookie when the token is gone, never queue it: the checkout request has pinned query counts and its cart is
 * claimed, the others do not change the cart). A logged-in customer's cart is keyed by account: such a request
 * neither restores nor writes the cookie (it may DELETE one, after the login merge consumed the token).
 *
 * THE MARKER COOKIE `easyco_has_cart` (value "1"): `easyco_cart` is HttpOnly, so the storefront script cannot see it, and
 * the XSRF-TOKEN cookie dies with the session. A guest returning after the session ended would therefore look like a
 * first-time visitor and see an empty header count and an empty cart page. The marker is the script's readable sign that a
 * restorable cart exists: NOT HttpOnly and NOT encrypted (listed in the EncryptCookies exceptions, bootstrap/app.php) ON
 * PURPOSE, same path/domain/Secure/SameSite and the SAME lifetime as `easyco_cart`, queued, refreshed and deleted at exactly
 * the same moments (cookies()/forgetCookies() below are the only two places, so the two cannot diverge). It carries no
 * token and the server never reads it for anything: it is not a credential and is worth nothing to anyone who copies it.
 *
 * Only for requests with a session (Sanctum stateful); anything else passes through untouched. Applied to the API routes
 * that read or write the guest cart token. NEVER to a storefront page: those stay cookie-free.
 */
final class PersistGuestCartToken
{
    public const COOKIE = 'easyco_cart';

    /** The script-readable "a cart can be restored" marker; its value is always "1". */
    public const MARKER = 'easyco_has_cart';

    public const DEFAULT_DAYS = 7;

    /** The route changes the cart (add, change, remove, promotion): the cookie is refreshed with the row's life. */
    public const WRITE = 'write';

    /** The route only reads the cart: the cookie is queued only when the request carried none. */
    public const READ = 'read';

    /** The route reads the token for something else (checkout, shipping quote, login, register): restore and delete only. */
    public const PASSIVE = 'passive';

    public function handle(Request $request, Closure $next, string $mode = self::READ): Response
    {
        if (! $request->hasSession()) {
            return $next($request);
        }

        $session = $request->session();
        $signedIn = Auth::guard('customer')->check();

        if (! $signedIn && ! $session->has('cart_token')) {
            $carried = $request->cookies->get(self::COOKIE);

            if (is_string($carried) && Str::isUuid($carried)) {
                $session->put('cart_token', $carried);
            }
        }

        $response = $next($request);

        // Re-read: the controller may have just logged the customer in (the guard now says so).
        $token = $session->get('cart_token');
        // Both cookies present = nothing to add; either one present = something to delete when the token is gone.
        $hadBoth = $request->cookies->has(self::COOKIE) && $request->cookies->has(self::MARKER);
        $hadAny = $request->cookies->has(self::COOKIE) || $request->cookies->has(self::MARKER);

        if ($token === null) {
            if ($hadAny) {
                $this->forgetCookies();
            }

            return $response;
        }

        if (Auth::guard('customer')->check() || ! is_string($token)) {
            return $response;
        }

        // A passive route never queues (checkout has a pinned query count and its cart is claimed anyway); a read route
        // queues only for a request that lacks one of the two cookies; only a write refreshes existing ones.
        if ($mode === self::PASSIVE || ($mode === self::READ && $hadBoth)) {
            return $response;
        }

        $minutes = $this->minutesLeft($token);

        if ($minutes !== null) {
            $this->queueCookies($token, $minutes);
        }

        return $response;
    }

    /** THE one place the two cookies are written: the encrypted HttpOnly token cookie and the readable marker, one lifetime. */
    private function queueCookies(string $token, int $minutes): void
    {
        Cookie::queue(Cookie::make(self::COOKIE, $token, $minutes, '/', config('session.domain'), config('session.secure'), true, false, 'lax'));
        Cookie::queue(Cookie::make(self::MARKER, '1', $minutes, '/', config('session.domain'), config('session.secure'), false, false, 'lax'));
    }

    /** THE one place the two cookies are deleted. */
    private function forgetCookies(): void
    {
        Cookie::queue(Cookie::forget(self::COOKIE, '/', config('session.domain')));
        Cookie::queue(Cookie::forget(self::MARKER, '/', config('session.domain')));
    }

    /** The cookie's lifetime in minutes: the configured days, never more than the live cart row has left; null = no live row. */
    private function minutesLeft(string $token): ?int
    {
        $expires = CartModel::query()->where('session_token', $token)->value('expires_at');

        if ($expires === null) {
            return null;
        }

        $configured = max(1, (int) config('cart.guest_cookie_days', self::DEFAULT_DAYS)) * 1440;
        $remaining = (int) floor(Carbon::now()->diffInMinutes(Carbon::parse($expires), false));

        return $remaining < 1 ? null : min($configured, $remaining);
    }
}
